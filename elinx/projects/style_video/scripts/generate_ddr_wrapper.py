"""Generate the public DDR frame-buffer boundary from the core's real ports."""
from pathlib import Path
from build_docs import parse_module

ROOT=Path(__file__).resolve().parents[1]


def generate():
    source=ROOT/'rtl/style_platform_core.sv'
    module=parse_module(source)
    text=source.read_text(encoding='utf-8')
    header=text[:text.index('\nwire [ID_WIDTH-1:0] cw_awid;')]
    header=header[header.index('module style_platform_core'):]
    header=header.replace('module style_platform_core','module style_ddr_framebuffer',1).replace('output reg ','output wire ')
    connections=',\n'.join('        .'+name+'('+name+')' for name,_,_ in module['ports'])
    params=',\n'.join('        .'+name+'('+name+')' for name,_ in module['parameters'])
    output='''// Generated by scripts/generate_ddr_wrapper.py. Public frame-memory boundary.
// Owns capture/job/display DMA, frame slots, APB control and the CNN RGB ports
// through the existing verified core. Efinix DDR3 controller/PHY is board-owned.
// AXI128 RGBX storage: word=0x00RRGGBB, first pixel in bits31:0.
'''+header+'\n    style_platform_core #(\n'+params+'\n    ) core(\n'+connections+'\n    );\nendmodule\n'
    (ROOT/'rtl/style_ddr_framebuffer.sv').write_text(output,encoding='utf-8')


if __name__=='__main__':generate()
