"""Generate the self-contained RGB8 display-encoding approximation.

The offline tables use Python binary64 math and explicit round-half-up:
    y = floor(255 * (x / 255) ** (10 / GAMMA_TENTHS) + 0.5)
The default GAMMA_TENTHS=18 is gentler than the retained gamma22 table.
No floating point, power operation or external memory file is used in hardware.
--check is read-only: the checked-in RTL must match the expected UTF-8 bytes.
"""
import argparse
import hashlib
import json
import math
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parent.parent
TARGET = ROOT / "rtl/style_rgb_gamma.sv"
PROFILE = ROOT / "build/gamma_profile.json"
DEFAULT_GAMMA_TENTHS = 18
SUPPORTED_GAMMA_TENTHS = (18, 22)
ANCHOR_INPUTS = (0, 1, 4, 16, 32, 64, 128, 192, 255)
FORMULA = "floor(255 * (x / 255) ** (10 / GAMMA_TENTHS) + 0.5), x=0..255"


def table_values(gamma_tenths=DEFAULT_GAMMA_TENTHS):
    assert gamma_tenths in SUPPORTED_GAMMA_TENTHS
    table = [math.floor(255.0 * math.pow(x / 255.0, 10.0 / gamma_tenths) + 0.5) for x in range(256)]
    assert table[0] == 0 and table[-1] == 255
    assert all(0 <= y <= 255 for y in table)
    assert all(a <= b for a, b in zip(table, table[1:]))
    return table


def rtl_bytes(tables):
    lines = [
        "// Generated by scripts/generate_gamma.py; edit the generator, then regenerate.",
        "// Display-encoding approximation, not white balance or a complete ISP.",
        "// The same curve on RGB does not calibrate sensor colors; shadow noise may increase.",
        "// Offline round-half-up: floor(255 * (x/255) ** (10/GAMMA_TENTHS) + 0.5).",
        "// GAMMA_TENTHS selects 18 (gentler default) or the retained 22 curve.",
        "// Pure combinational lookup: no clock, handshake, pipeline or external memory file.",
        "module style_rgb_gamma #(",
        "    parameter integer ENABLE = 1,",
        f"    parameter integer GAMMA_TENTHS = {DEFAULT_GAMMA_TENTHS}",
        ") (",
        "    input wire [23:0] s_rgb,",
        "    output wire [23:0] m_rgb",
        ");",
    ]
    for gamma_tenths in SUPPORTED_GAMMA_TENTHS:
        function = f"gamma8_{gamma_tenths}"
        lines += [
            f"    function [7:0] {function};",
            "        input [7:0] value;",
            "        begin",
            "            case (value)",
        ]
        lines += [f"                8'd{x}: {function} = 8'd{y};" for x, y in enumerate(tables[gamma_tenths])]
        lines += [
            f"                default: {function} = 8'd0;",
            "            endcase",
            "        end",
            "    endfunction",
        ]
    lines += [
        "    generate",
        "        if (ENABLE == 0) begin : passthrough",
        "            assign m_rgb = s_rgb;",
        "        end else if (GAMMA_TENTHS == 18) begin : encoded18",
        "            assign m_rgb = {gamma8_18(s_rgb[23:16]), gamma8_18(s_rgb[15:8]), gamma8_18(s_rgb[7:0])};",
        "        end else begin : encoded22",
        "            assign m_rgb = {gamma8_22(s_rgb[23:16]), gamma8_22(s_rgb[15:8]), gamma8_22(s_rgb[7:0])};",
        "        end",
        "    endgenerate",
        "`ifndef SYNTHESIS",
        "    initial begin",
        "        if (ENABLE != 0 && GAMMA_TENTHS != 18 && GAMMA_TENTHS != 22)",
        "            $fatal(1, \"GAMMA_TENTHS must be 18 or 22 when enabled\");",
        "    end",
        "`endif",
        "endmodule",
    ]
    return ("\n".join(lines) + "\n").encode("utf-8")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Validate exact generated RTL bytes without writing files")
    args = parser.parse_args()
    tables = {gamma: table_values(gamma) for gamma in SUPPORTED_GAMMA_TENTHS}
    table_sha = {gamma: hashlib.sha256(bytes(table)).hexdigest() for gamma, table in tables.items()}
    expected = rtl_bytes(tables)
    # Preserve the exact previous gamma22 curve, not merely a similar formula.
    assert table_sha[22] == "a6ddab81d634168b433b48261011f3b79170078a8300b7b000fea91b9b016a8f"
    if args.check:
        if not TARGET.is_file() or TARGET.read_bytes() != expected:
            print(f"Gamma RTL is absent or differs from the generator: {TARGET}", file=sys.stderr)
            return 1
        print(f"PASS GAMMA GENERATOR: 2 x 256 entries, default gamma18, RTL exact match; SHA256={table_sha}")
        return 0
    TARGET.parent.mkdir(parents=True, exist_ok=True)
    TARGET.write_bytes(expected)
    profile = {
        "profile": "selectable_gamma_display_encoding_approximation",
        "default_gamma_tenths": DEFAULT_GAMMA_TENTHS,
        "supported_gamma_tenths": list(SUPPORTED_GAMMA_TENTHS),
        "formula": FORMULA,
        "input_bits": 8,
        "output_bits": 8,
        "entry_count_per_profile": 256,
        "offline_math": "Python math.pow binary64; integer floor(value+0.5), round-half-up",
        "quantization": "RGB channels independently use the same unsigned 8-bit lookup",
        "table_sha256_encoding": "256 unsigned bytes ordered by input code 0..255",
        "profiles": {
            f"gamma{gamma}": {
                "gamma_tenths": gamma,
                "formula": f"floor(255 * (x / 255) ** (10 / {gamma}) + 0.5), x=0..255",
                "exponent": f"10/{gamma}",
                "entry_count": len(table),
                "table_sha256": table_sha[gamma],
                "table_values": table,
                "anchors": {str(x): table[x] for x in ANCHOR_INPUTS},
            }
            for gamma, table in tables.items()
        },
        "rtl_path": TARGET.relative_to(ROOT).as_posix(),
        "rtl_sha256": hashlib.sha256(expected).hexdigest(),
        "generator_path": Path(__file__).resolve().relative_to(ROOT).as_posix(),
        "generator_sha256": hashlib.sha256(Path(__file__).read_bytes()).hexdigest(),
        "external_memory_dependency": False,
        "hardware_floating_point": False,
        "pipeline_cycles": 0,
        "bypass": "ENABLE=0 passes all 24 RGB bits unchanged",
        "white_balance_calibrated": False,
        "complete_isp": False,
        "hardware_verified": False,
        "limitations": "Display encoding approximation; identical channel curves do not calibrate sensor colors and may expose shadow noise.",
    }
    PROFILE.parent.mkdir(parents=True, exist_ok=True)
    PROFILE.write_text(json.dumps(profile, indent=2) + "\n", encoding="utf-8")
    print(f"Generated {TARGET}: 2 x 256 entries, default gamma18, table SHA256={table_sha}")
    print(f"Profile: {PROFILE}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
